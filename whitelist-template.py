#!/usr/bin/env python3
# ============================================================================
# 放行名单样板 —— 复制到你自己的仓库改，然后把 raw 链接填进：
#   bgpeer 面板 → 10 屏蔽中国域名和IP → 3 自定义放行名单脚本链接
# ============================================================================
#
# 怎么用（三步）：
#   1. 把本文件复制到你自己的 GitHub 仓库（文件名随意，扩展名 .py 或 .txt 都行）
#   2. 改下面三个列表成你要的
#   3. 复制它的 raw 链接（必须是 raw 链接，不是网页的 blob 链接）填进菜单 10 → 3
#      形如：https://raw.githubusercontent.com/你的名字/你的仓库/main/whitelist.py
#
# ⚠ 脚本只【解析】这个文件取出下面三个列表，绝不会执行它。
#   所以：只写字面量字符串，别写变量拼接、函数调用、f-string——那些取不到值会被忽略。
#   每一条都会逐个校验，写错的会跳过并在终端提示，不会污染配置、不会让节点出问题。
#
# 改完不用等每天 03:00 的定时刷新，进菜单点「5 立即更新」即时生效。
# ============================================================================


