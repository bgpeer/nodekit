#!/usr/bin/env python3
"""net-optimize 4.5.27 —— mangle 只删自己的规则 + MSS 往下探、兜底往小了报：
  (3) 开机恢复原来 `-F POSTROUTING` 整表 flush、持久化文件整段剥 *mangle，会清掉
      别的软件的规则。改成按特征只删自己的（TCPMSS + 老版本 DSCP，PAT_OWN_MANGLE），
      持久化文件里只删自己的那几行、别的规则留着，空表才拿掉整个 *mangle 段。
  (4) MSS 探测原来只探到 MTU 1420，全失败就兜底 1452（等于认定 MTU 1492，往大了报会
      黑洞）。探测一路探到 MTU 1280（IPv6 最小 MTU），探不到改用保守兜底 MSS 1240。
  另核查：detect_ipt_backend 试写 MSS-9999 中途被杀会留残渣——试写前先清掉上次的残渣，
      残渣也不会再让计数误认后端；detect_outbound_iface 的 /sys 兜底只在路由全拿不到时
      才触发，有默认路由的机器照样走路由结果（本测试第 6 节钉住这一点）。
"""
import os, re, sys, io, contextlib, importlib.util
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
spec = importlib.util.spec_from_file_location("netopt", os.path.join(ROOT, "net-optimize.py"))
m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
src = open(os.path.join(ROOT, "net-optimize.py"), encoding="utf-8").read()
_orig_detect_ipt = m.detect_ipt_backend       # 第 2 节会把它们换成桩，用前先恢复
_orig_detect_iface = m.detect_outbound_iface
_orig_ipt_count = m.ipt_count
_orig_ipt_rules = m.ipt_rules
bad = 0
def check(l, ok):
    global bad; bad += not ok; print(("  ✔ " if ok else "  ✖ ") + l)

def R(rc=0, out=""):
    return type("R", (), {"returncode": rc, "stdout": out, "stderr": ""})()

# ── 1. 探测梯子：探到 MTU 1280 ─────────────────────────────────────────────
def mkrun_ping(limit):
    def _run(cmd, **kw):
        size = int(cmd[cmd.index("-s") + 1])
        return R(0 if size <= limit else 1)
    return _run

check("探测梯子一路到 1280（载荷 1252）",
      m.MSS_PROBE_SIZES == (1472, 1452, 1424, 1392, 1352, 1292, 1252))
check("保守兜底 = 最小探测 MTU 1280 - 40",
      m.MSS_FALLBACK == 1240 == min(m.MSS_PROBE_SIZES) + 28 - 40)
m.run = mkrun_ping(1392)
check("MTU 1420 的老路径照样量得出", m.probe_path_mtu("ping") == 1420)
m.run = mkrun_ping(1292)
check("更小 MTU 1320 现在量得出（原来全失败）", m.probe_path_mtu("ping") == 1320)
m.run = mkrun_ping(1252)
check("最小 MTU 1280 量得出", m.probe_path_mtu("ping") == 1280)
m.run = mkrun_ping(0)
check("全失败返回 0（不谎报）", m.probe_path_mtu("ping") == 0)
m._ping_with_df = lambda: "ping"
m.run = mkrun_ping(1252)
check("检测版快速探测也探到 1280", m.probe_path_mtu_quick() == 1280)

# ── 2. setup_mss_clamping：探不到用保守兜底，不再用 1452 ───────────────────
def run_setup(probe_mtu, have_ping=True):
    written, cleared, added = {}, [], []
    m.Cfg.ENABLE_MSS_CLAMP = True
    m.Cfg.MSS_AUTO = True
    m.Cfg.MSS_USER_SET = False
    m.Cfg.MSS_VALUE = 1452
    m.Cfg.ENABLE_IPV6_MSS = False
    m.have_cmd = lambda c: (c != "ping") if not have_ping else True
    m._ping_with_df = lambda: "ping"
    m.probe_path_mtu = lambda p: probe_mtu
    m.detect_outbound_iface = lambda: "eth0"
    m.detect_ipt_backend = lambda: "iptables"
    m.run = lambda *a, **k: R(0)
    m.read_text = lambda p, default="": ""
    m.write_text = lambda p, c, **k: written.__setitem__(p, c)
    m.ipt_clear = lambda cmds, pat, **k: cleared.append(pat)
    m.apply_one_tcpmss = lambda *a: (added.append(a), True)[1]
    m.ipt_dedup = lambda *a, **k: None
    m.ipt_count = lambda *a, **k: 1
    out = io.StringIO()
    with contextlib.redirect_stdout(out):
        m.setup_mss_clamping()
    return written.get(m.CONFIG_FILE, ""), out.getvalue()

cfg, out = run_setup(0)
check("探测全失败：config 写进保守兜底 MSS=1240（不是 1452）",
      "MSS_VALUE=1240" in cfg and "MSS_VALUE=1452" not in cfg)
check("探测全失败：屏上说保守兜底", "保守兜底 MSS=1240" in out)
cfg, _ = run_setup(1320)
check("探到 MTU 1320：MSS=1280", "MSS_VALUE=1280" in cfg)
cfg, _ = run_setup(1280)
check("探到最小 MTU 1280：MSS=1240", "MSS_VALUE=1240" in cfg)
cfg, _ = run_setup(1500)
check("探到 MTU 1500：MSS=1460 不变", "MSS_VALUE=1460" in cfg)
cfg, out = run_setup(0, have_ping=False)
check("没有 ping 可用：同样保守兜底 1240", "MSS_VALUE=1240" in cfg)

# ── 3. strip_persistent_mangle：只剥自己的行，别人的 MARK 和 nat 都留着 ────
V4 = ("# Generated by iptables-save\n*filter\n:INPUT ACCEPT [0:0]\nCOMMIT\n"
      "*nat\n:POSTROUTING ACCEPT [0:0]\n"
      "-A POSTROUTING -p tcp --dport 8443 -j MASQUERADE\nCOMMIT\n"
      "*mangle\n:POSTROUTING ACCEPT [0:0]\n"
      "-A POSTROUTING -p tcp --tcp-flags SYN,RST SYN -j TCPMSS --set-mss 1380\n"
      "-A POSTROUTING -p tcp -j MARK --set-mark 0x1\n"
      "-A POSTROUTING -j DSCP --set-dscp-class EF\nCOMMIT\n")
V6 = ("*mangle\n:POSTROUTING ACCEPT [0:0]\n"
      "-A POSTROUTING -p tcp --tcp-flags SYN,RST SYN -j TCPMSS --set-mss 1380\nCOMMIT\n"
      "*nat\n:POSTROUTING ACCEPT [0:0]\n-A POSTROUTING -j MASQUERADE\nCOMMIT\n")
files = {"/etc/iptables/rules.v4": V4, "/etc/iptables/rules.v6": V6}
m.read_text = lambda p, default="": files.get(p, default)
m.write_text = lambda p, c, **k: files.__setitem__(p, c)
got = list(m.strip_persistent_mangle())
check("两边都动了才各报一次", sorted(got) == ["/etc/iptables/rules.v4", "/etc/iptables/rules.v6"])
v4 = files["/etc/iptables/rules.v4"]
check("v4：自己的 TCPMSS / DSCP 行没了", "TCPMSS" not in v4 and "DSCP" not in v4)
check("v4：别人的 MARK 规则留着，*mangle 段还在",
      "-j MARK --set-mark 0x1" in v4 and "*mangle" in v4)
check("v4：nat 端口跳跃规则不动", "-j MASQUERADE" in v4 and "*nat" in v4)
v6 = files["/etc/iptables/rules.v6"]
check("v6：mangle 只剩自己的规则时空段整个拿掉", "*mangle" not in v6)
check("v6：nat 段不动", "*nat" in v6 and "-j MASQUERADE" in v6)
files = {"/etc/iptables/rules.v4": "*filter\n:INPUT ACCEPT [0:0]\nCOMMIT\n",
         "/etc/iptables/rules.v6": ""}
check("没有 mangle 段：不动文件、不报错", list(m.strip_persistent_mangle()) == []
      and files["/etc/iptables/rules.v4"].startswith("*filter"))

# ── 4. 开机恢复：源码层不再有 -F，用按特征清 ───────────────────────────────
boot = src[src.index("def cmd_boot_apply"):src.index("# === 状态检查 ===")]
boot_code = "\n".join(l.split("#", 1)[0] for l in boot.splitlines())  # 只看代码，不看注释
check("开机恢复不再 -F 整表 flush", '"-F"' not in boot_code)
check("开机恢复按特征只清自己的规则", "ipt_clear(V4_CMDS + V6_CMDS, PAT_OWN_MANGLE)" in boot_code)
check("开机恢复缺 MSS_VALUE 时默认保守兜底",
      "str(MSS_FALLBACK)" in boot_code and '"1452"' not in boot_code)
check("clean_old_config / --reset 也走同一个特征常量",
      src.count("PAT_OWN_MANGLE") >= 4)  # 定义 + clean + boot + reset

# ── 5. detect_ipt_backend：残渣先清，不再误认后端 ──────────────────────────
TEST_LINE = "-A POSTROUTING -p tcp --tcp-flags SYN,RST SYN -j TCPMSS --set-mss 9999"
def mk_ipt_run(rules, fail_add=()):
    def _run(cmd, **kw):
        c0 = cmd[0]
        if "-S" in cmd:    # -S 有两种写法：直接 -S，和 ipt_rules 带的 -w 2 -S
            return R(0, "\n".join(rules[c0]) + "\n")
        rest = " ".join(cmd[cmd.index("POSTROUTING") + 1:])
        if "-A" in cmd:
            if c0 in fail_add:
                return R(1)
            rules[c0].append("-A POSTROUTING " + rest)
            return R(0)
        if "-D" in cmd:
            line = "-A POSTROUTING " + rest
            if line in rules[c0]:
                rules[c0].remove(line)
            return R(0)
        return R(0)
    return _run

m.detect_ipt_backend = _orig_detect_ipt
m.ipt_count = _orig_ipt_count
m.ipt_rules = _orig_ipt_rules
m.have_cmd = lambda c: c in ("iptables", "iptables-legacy")
rules = {"iptables": [TEST_LINE], "iptables-legacy": []}   # 上次被杀留下的残渣
m.run = mk_ipt_run(rules, fail_add=("iptables",))
check("残渣 + 本次试写失败：不再把残渣当成功，不误认 iptables",
      m.detect_ipt_backend() == "iptables-legacy")
check("残渣已被试写前的清理带走", TEST_LINE not in rules["iptables"]
      and TEST_LINE not in rules["iptables-legacy"])
rules = {"iptables": [], "iptables-legacy": []}
m.run = mk_ipt_run(rules)
check("干净时试写成功：认出 iptables", m.detect_ipt_backend() == "iptables")
check("试写完不留 9999 规则", TEST_LINE not in rules["iptables"]
      and TEST_LINE not in rules["iptables-legacy"])

# ── 6. detect_outbound_iface 核查：有默认路由时走路由，不走 /sys 兜底 ──────
m.detect_outbound_iface = _orig_detect_iface
m.run = lambda cmd, **kw: R(0, "1.1.1.1 via _gw_ dev eth1 src _src_ uid 0\n    cache"
                             if cmd == ["ip", "-4", "route", "get", "1.1.1.1"] else "")
m.read_text = lambda p, default="": ("Iface\tDestination\t...\n" if p == "/proc/net/route"
                                     else "up\n")
m.os.listdir = lambda p: ["lo", "eth0", "eth1"]   # eth0 排在前面、也是 UP 的
check("多网卡 + 有默认路由：返回路由的 eth1，不乱挑排前面的 eth0",
      m.detect_outbound_iface() == "eth1")

# ── 7. 版本号 ───────────────────────────────────────────────────────────────
mv = tuple(int(x) for x in re.findall(r"\d+", re.search(r'^VERSION = "([\d.]+)"', src, re.M).group(1)))
check("VERSION ≥ 4.5.27", mv >= (4, 5, 27))

print("ALL PASS" if not bad else f"{bad} 项没过"); sys.exit(1 if bad else 0)
